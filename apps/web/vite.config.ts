import { fileURLToPath, URL } from 'node:url'
import tailwindcss from '@tailwindcss/vite'
import vue from '@vitejs/plugin-vue'
import { defineConfig } from 'vite'

const API_PORT = process.env.CLOUDATLAS_PORT ?? '5174'

export default defineConfig({
  plugins: [vue(), tailwindcss()],
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  // The shared package is published as TypeScript source, so let Vite compile
  // it with the app instead of trying to pre-bundle it.
  optimizeDeps: { exclude: ['@cloudatlas/shared'] },
  server: {
    host: '127.0.0.1',
    port: 5173,
    strictPort: true,
    proxy: {
      '/api': {
        target: `http://127.0.0.1:${API_PORT}`,
        changeOrigin: false,
      },
    },
  },
  build: { target: 'es2022', sourcemap: true },
})
